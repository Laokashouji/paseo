#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const DEFAULT_IOS_APP_NAME = "Paseo Fork";
export const DEFAULT_IOS_URL_SCHEME = "paseo-fork";

const BUNDLE_ID_RE = /^[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)+$/;
const URL_SCHEME_RE = /^[a-z][a-z0-9+.-]*$/;
const BUILD_NUMBER_RE = /^[0-9]+(\.[0-9]+){0,2}$/;
const VALID_APS_MODES = new Set(["production", "development", "none"]);

export function validateIosConfigOptions(options) {
  const bundleId = String(options.bundleId ?? "").trim();
  if (!BUNDLE_ID_RE.test(bundleId)) {
    throw new Error(
      `Invalid iOS bundleId "${bundleId}". Expected reverse-DNS format like com.example.paseo.`,
    );
  }
  if (bundleId === "sh.paseo" || bundleId === "sh.paseo.debug") {
    throw new Error(
      `Refusing to use upstream bundleId "${bundleId}". Configure your own Apple Developer Bundle ID (e.g. com.laokashouji.paseo).`,
    );
  }

  const appName = String(options.appName ?? DEFAULT_IOS_APP_NAME).trim();
  if (!appName) {
    throw new Error("appName must be a non-empty string.");
  }

  const scheme = String(options.scheme ?? DEFAULT_IOS_URL_SCHEME).trim();
  if (!URL_SCHEME_RE.test(scheme)) {
    throw new Error(
      `Invalid URL scheme "${scheme}". Expected lowercase RFC 3986 scheme like paseo-fork.`,
    );
  }

  const apsEnvironment = String(options.apsEnvironment ?? "production").trim();
  if (!VALID_APS_MODES.has(apsEnvironment)) {
    throw new Error(
      `Invalid apsEnvironment "${apsEnvironment}". Expected one of: production, development, none.`,
    );
  }

  const buildNumber =
    options.buildNumber === undefined || options.buildNumber === null
      ? null
      : String(options.buildNumber).trim() || null;
  if (buildNumber !== null && !BUILD_NUMBER_RE.test(buildNumber)) {
    throw new Error(
      `Invalid buildNumber "${buildNumber}". Expected Apple CFBundleVersion numeric format (e.g. 17531999).`,
    );
  }

  const expoProjectId = String(options.expoProjectId ?? "").trim() || null;
  const expoOwner = String(options.expoOwner ?? "").trim() || null;

  return {
    bundleId,
    appName,
    scheme,
    apsEnvironment,
    buildNumber,
    expoProjectId,
    expoOwner,
  };
}

/**
 * Pure transformation function applied on top of upstream packages/app/app.config.js.
 * Kept self-contained so it can be unit-tested directly and embedded inside the ephemeral wrapper.
 */
export function transformExpoConfig(rawConfig, rawOptions) {
  const options = validateIosConfigOptions(rawOptions);
  const root =
    rawConfig && typeof rawConfig === "object" && "expo" in rawConfig
      ? rawConfig
      : { expo: rawConfig };
  const upstreamExpo = root.expo;
  if (!upstreamExpo || typeof upstreamExpo !== "object") {
    throw new Error("Upstream app.config.js did not export a valid expo object.");
  }

  const nextExpo = {
    ...upstreamExpo,
    name: options.appName,
    scheme: options.scheme,
    ios: {
      ...upstreamExpo.ios,
      bundleIdentifier: options.bundleId,
      infoPlist: {
        ...upstreamExpo.ios?.infoPlist,
        CFBundleDisplayName: options.appName,
        ITSAppUsesNonExemptEncryption: false,
      },
    },
    extra: {
      ...upstreamExpo.extra,
    },
    plugins: Array.isArray(upstreamExpo.plugins) ? [...upstreamExpo.plugins] : [],
  };

  // Never inherit upstream Firebase plist path.
  delete nextExpo.ios.googleServicesFile;

  if (options.buildNumber !== null) {
    nextExpo.ios.buildNumber = options.buildNumber;
  }

  // Align aps-environment entitlement with the signing provisioning profile.
  const nextEntitlements = { ...nextExpo.ios.entitlements };
  if (options.apsEnvironment === "none") {
    delete nextEntitlements["aps-environment"];
    if (Object.keys(nextEntitlements).length > 0) {
      nextExpo.ios.entitlements = nextEntitlements;
    } else {
      delete nextExpo.ios.entitlements;
    }
  } else {
    nextEntitlements["aps-environment"] = options.apsEnvironment;
    nextExpo.ios.entitlements = nextEntitlements;
  }

  // Configure or clear EAS ownership so builds never query upstream getpaseo's EAS project.
  if (options.expoProjectId) {
    nextExpo.extra.eas = {
      ...nextExpo.extra.eas,
      projectId: options.expoProjectId,
    };
    if (options.expoOwner) {
      nextExpo.owner = options.expoOwner;
    } else {
      delete nextExpo.owner;
    }
  } else {
    delete nextExpo.owner;
    delete nextExpo.extra.eas;
  }

  return { ...root, expo: nextExpo };
}

function renderWrapperAppConfig(upstreamCjsRelPath, options) {
  const serializedOptions = JSON.stringify(options, null, 2);
  return `// Ephemeral fork iOS config overlay generated by scripts/fork/prepare-ios-config.mjs.
// Do NOT commit this file; run "node scripts/fork/prepare-ios-config.mjs --restore" to revert.
const upstreamExport = require(${JSON.stringify(upstreamCjsRelPath)});
const upstreamConfig =
  upstreamExport && typeof upstreamExport === "object" && "default" in upstreamExport
    ? upstreamExport.default
    : upstreamExport;

const FORK_IOS_OPTIONS = ${serializedOptions};

function applyForkIosOverrides(rawConfig) {
  const root =
    rawConfig && typeof rawConfig === "object" && "expo" in rawConfig
      ? rawConfig
      : { expo: rawConfig };
  const upstreamExpo = root.expo;
  const nextExpo = {
    ...upstreamExpo,
    name: FORK_IOS_OPTIONS.appName,
    scheme: FORK_IOS_OPTIONS.scheme,
    ios: {
      ...(upstreamExpo.ios || {}),
      bundleIdentifier: FORK_IOS_OPTIONS.bundleId,
      infoPlist: {
        ...((upstreamExpo.ios && upstreamExpo.ios.infoPlist) || {}),
        CFBundleDisplayName: FORK_IOS_OPTIONS.appName,
        ITSAppUsesNonExemptEncryption: false,
      },
    },
    extra: {
      ...(upstreamExpo.extra || {}),
    },
    plugins: Array.isArray(upstreamExpo.plugins) ? [...upstreamExpo.plugins] : [],
  };

  delete nextExpo.ios.googleServicesFile;

  if (FORK_IOS_OPTIONS.buildNumber) {
    nextExpo.ios.buildNumber = FORK_IOS_OPTIONS.buildNumber;
  }

  const nextEntitlements = { ...((nextExpo.ios && nextExpo.ios.entitlements) || {}) };
  if (FORK_IOS_OPTIONS.apsEnvironment === "none") {
    delete nextEntitlements["aps-environment"];
    if (Object.keys(nextEntitlements).length > 0) {
      nextExpo.ios.entitlements = nextEntitlements;
    } else {
      delete nextExpo.ios.entitlements;
    }
    // Expo config-plugin mods execute LIFO, so unshift runs AFTER expo-notifications
    // and strips aps-environment when the provisioning profile has no Push capability.
    const { withEntitlementsPlist } = require("expo/config-plugins");
    nextExpo.plugins.unshift((cfg) =>
      withEntitlementsPlist(cfg, (mod) => {
        if (mod.modResults && typeof mod.modResults === "object") {
          delete mod.modResults["aps-environment"];
        }
        return mod;
      }),
    );
  } else {
    nextEntitlements["aps-environment"] = FORK_IOS_OPTIONS.apsEnvironment;
    nextExpo.ios.entitlements = nextEntitlements;
  }

  if (FORK_IOS_OPTIONS.expoProjectId) {
    nextExpo.extra.eas = {
      ...(nextExpo.extra.eas || {}),
      projectId: FORK_IOS_OPTIONS.expoProjectId,
    };
    if (FORK_IOS_OPTIONS.expoOwner) {
      nextExpo.owner = FORK_IOS_OPTIONS.expoOwner;
    } else {
      delete nextExpo.owner;
    }
  } else {
    delete nextExpo.owner;
    delete nextExpo.extra.eas;
  }

  return { ...root, expo: nextExpo };
}

module.exports = applyForkIosOverrides(upstreamConfig);
`;
}

function convertUpstreamConfigToCjs(sourceText) {
  if (!/\bexport\s+default\b/.test(sourceText)) {
    return sourceText;
  }
  return sourceText.replace(/\bexport\s+default\b/, "module.exports =");
}

export function applyIosConfigOverlay({ appDir, ...rawOptions }) {
  const options = validateIosConfigOptions(rawOptions);
  const configPath = path.join(appDir, "app.config.js");
  const backupPath = path.join(appDir, "app.config.upstream.backup.js");
  const upstreamCjsPath = path.join(appDir, "app.config.upstream.cjs");

  if (!fs.existsSync(configPath)) {
    throw new Error(`Expected app.config.js at ${configPath}`);
  }

  // Preserve original upstream bytes once so repeated invocations stay idempotent.
  if (!fs.existsSync(backupPath)) {
    fs.copyFileSync(configPath, backupPath);
  }

  const originalSource = fs.readFileSync(backupPath, "utf8");
  fs.writeFileSync(upstreamCjsPath, convertUpstreamConfigToCjs(originalSource), "utf8");
  fs.writeFileSync(
    configPath,
    renderWrapperAppConfig("./app.config.upstream.cjs", options),
    "utf8",
  );

  return {
    configPath,
    backupPath,
    upstreamCjsPath,
    options,
  };
}

export function restoreIosConfigOverlay({ appDir }) {
  const configPath = path.join(appDir, "app.config.js");
  const backupPath = path.join(appDir, "app.config.upstream.backup.js");
  const upstreamCjsPath = path.join(appDir, "app.config.upstream.cjs");

  let restored = false;
  if (fs.existsSync(backupPath)) {
    fs.copyFileSync(backupPath, configPath);
    fs.rmSync(backupPath, { force: true });
    restored = true;
  }
  if (fs.existsSync(upstreamCjsPath)) {
    fs.rmSync(upstreamCjsPath, { force: true });
  }
  return { restored, configPath };
}

const CLI_VALUE_FLAGS = {
  "--app-dir": (opts, v) => {
    opts.appDir = path.resolve(v);
  },
  "--bundle-id": (opts, v) => {
    opts.bundleId = v;
  },
  "--app-name": (opts, v) => {
    opts.appName = v;
  },
  "--scheme": (opts, v) => {
    opts.scheme = v;
  },
  "--aps-environment": (opts, v) => {
    opts.apsEnvironment = v;
  },
  "--build-number": (opts, v) => {
    opts.buildNumber = v;
  },
  "--expo-project-id": (opts, v) => {
    opts.expoProjectId = v;
  },
  "--expo-owner": (opts, v) => {
    opts.expoOwner = v;
  },
};

function parseCliArgs(argv) {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
  const options = {
    appDir: path.join(repoRoot, "packages/app"),
    restore: false,
    help: false,
    bundleId: process.env.IOS_BUNDLE_ID ?? "",
    appName: process.env.IOS_APP_NAME || DEFAULT_IOS_APP_NAME,
    scheme: process.env.IOS_URL_SCHEME || DEFAULT_IOS_URL_SCHEME,
    apsEnvironment: process.env.IOS_APS_ENVIRONMENT || "production",
    buildNumber: process.env.IOS_BUILD_NUMBER || null,
    expoProjectId: process.env.IOS_EXPO_PROJECT_ID || "",
    expoOwner: process.env.IOS_EXPO_OWNER || "",
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg in CLI_VALUE_FLAGS) {
      CLI_VALUE_FLAGS[arg](options, argv[++i] ?? "");
    } else if (arg === "--restore") {
      options.restore = true;
    } else if (arg === "-h" || arg === "--help") {
      options.help = true;
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }

  return options;
}

function main() {
  const options = parseCliArgs(process.argv.slice(2));
  if (options.help) {
    console.log(`Usage: node scripts/fork/prepare-ios-config.mjs [options]

Ephemerally wrap packages/app/app.config.js with personal Fork iOS settings
(Bundle ID, display name, URL scheme, aps-environment, optional Expo project)
without modifying upstream-tracked files in git.

Options:
  --app-dir <dir>              Path to packages/app (default: <repo>/packages/app)
  --bundle-id <id>             Personal iOS Bundle ID (required unless --restore)
  --app-name <name>            Display name (default: "${DEFAULT_IOS_APP_NAME}")
  --scheme <scheme>            URL scheme (default: "${DEFAULT_IOS_URL_SCHEME}")
  --aps-environment <mode>     production | development | none (default: production)
  --build-number <num>         Override ios.buildNumber (default: native-release-version)
  --expo-project-id <uuid>     Optional personal EAS projectId for APNs push tokens
  --expo-owner <owner>         Optional personal Expo account owner
  --restore                    Restore original upstream app.config.js and clean temp files
  -h, --help                   Show this help message`);
    return;
  }

  if (options.restore) {
    const result = restoreIosConfigOverlay({ appDir: options.appDir });
    console.log(
      result.restored
        ? `Restored original upstream config at ${result.configPath}`
        : `No backup found; ${result.configPath} already clean.`,
    );
    return;
  }

  const result = applyIosConfigOverlay(options);
  console.log(`Applied ephemeral fork iOS config overlay to ${result.configPath}:`);
  console.log(`  bundleId       : ${result.options.bundleId}`);
  console.log(`  appName        : ${result.options.appName}`);
  console.log(`  scheme         : ${result.options.scheme}`);
  console.log(`  apsEnvironment : ${result.options.apsEnvironment}`);
  console.log(
    `  buildNumber    : ${result.options.buildNumber ?? "(from native-release-version)"}`,
  );
  console.log(
    `  expoPush       : ${result.options.expoProjectId ? `enabled (${result.options.expoProjectId})` : "disabled (no personal EAS projectId)"}`,
  );
}

function isExecutedDirectly() {
  if (!process.argv[1]) return false;
  try {
    return fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
  }
}

if (isExecutedDirectly()) {
  main();
}
