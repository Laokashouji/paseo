export function mergeMainChatStyleLocale(
  base: MainChatResource,
  locale: ExtraLocaleCode,
): MainChatResource {
  const override = MAIN_CHAT_STYLE_LOCALE_OVERRIDES[locale];
  const parityOverride = MAIN_CHAT_PARITY_LOCALE_OVERRIDES[locale];
  return {
    ...base,
    actions: {
      ...base.actions,
      ...override.actions,
    },
    backgroundTurn: {
      ...base.backgroundTurn,
      ...parityOverride.backgroundTurn,
    },
    actionBar: {
      ...base.actionBar,
      askCard: parityOverride.askCard,
    },
    settings: {
      ...base.settings,
      ...override.toasts,
      master: override.master,
      intervals: override.intervals,
      style: override.style,
    },
  };
}
